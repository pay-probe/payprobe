async def test_variant_lmk_enforces_key_separation():
    """With variant_lmk on, a CVK (variant 4) doesn't check out as a ZPK
    (variant 0): BU with the wrong key type yields a different KCV."""
    sim, port = await _start({"host": "127.0.0.1", "port": 0, "variant_lmk": True})
    try:
        gen = await _send(port, "A0", "1402U")  # CVK, variant 4
        token, kcv = gen["data"][:33], gen["data"][33:39]
        # BU as CVK (type 42 -> 402, variant 4) reproduces the KCV
        right = await _send(port, "BU", f"42 1{token}".replace(" ", ""))
        assert right["data"][:6] == kcv
        # BU as ZPK (type 01 -> 001, variant 0) gets a different clear key -> KCV
        wrong = await _send(port, "BU", f"011{token}")
        assert wrong["data"][:6] != kcv
    finally:
        await sim.stop()
