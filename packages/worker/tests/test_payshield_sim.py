async def test_ca_translates_pin_block_format_iso0_to_iso3():
    """CA reformats between ISO 9564-1 formats: an ISO-0 block under the TPK
    comes back as an ISO-3 block under the ZPK carrying the same PIN."""
    sim, port = await _start()
    try:
        tpk = (await _send(port, "A0", "1002U"))["data"][:33]
        zpk = (await _send(port, "A0", "1001U"))["data"][:33]
        pan, pin = "400000000000000002", "1234"
        clear_tpk = sim.ctx.lmk.unwrap(tpk)
        # source block is ISO-0 (format code 01)
        src_block = ct.pin_block_encode(pin, pan, clear_tpk, "0")["pin_block"]
        pan12 = "".join(c for c in pan if c.isdigit())[-13:-1]
        # src fmt 01 (ISO-0) -> dst fmt 47 (ISO-3)
        r = await _send(port, "CA", f"{tpk}{zpk}12{src_block}0147{pan12}")
        assert r["response"] == "CB" and r["error"] == "00"
        out_block = r["data"][2:18]
        clear_zpk = sim.ctx.lmk.unwrap(zpk)
        # decode the result as ISO-3 -> same PIN; decoding as ISO-0 would differ
        assert ct.pin_block_decode(out_block, pan, clear_zpk, "3")["pin"] == pin
    finally:
        await sim.stop()


async def test_ca_translates_pin_block_format_iso0_to_iso1():
    """ISO-1 carries no PAN, so the destination block decodes without one."""
    sim, port = await _start()
    try:
        tpk = (await _send(port, "A0", "1002U"))["data"][:33]
        zpk = (await _send(port, "A0", "1001U"))["data"][:33]
        pan, pin = "400000000000000002", "580211"
        clear_tpk = sim.ctx.lmk.unwrap(tpk)
        src_block = ct.pin_block_encode(pin, pan, clear_tpk, "0")["pin_block"]
        pan12 = "".join(c for c in pan if c.isdigit())[-13:-1]
        # src fmt 01 (ISO-0) -> dst fmt 05 (ISO-1)
        r = await _send(port, "CA", f"{tpk}{zpk}12{src_block}0105{pan12}")
        assert r["response"] == "CB" and r["error"] == "00"
        assert r["data"][:2] == "06"  # 6-digit PIN length
        out_block = r["data"][2:18]
        clear_zpk = sim.ctx.lmk.unwrap(zpk)
        assert ct.pin_block_decode(out_block, "", clear_zpk, "1")["pin"] == pin
    finally:
        await sim.stop()


async def test_a0_mints_aes_key():
    """A0 with an AES scheme tag (R = AES-128) mints a 16-byte AES key whose
    token round-trips through the LMK."""
    sim, port = await _start()
    try:
        gen = await _send(port, "A0", "1001R")  # AES-128 ZPK
        assert gen["response"] == "A1" and gen["error"] == "00"
        token = gen["data"][:33]
        assert token[0] == "R"
        assert len(sim.ctx.lmk.unwrap(token)) == 32  # 16 bytes = 32 hex
    finally:
        await sim.stop()


async def test_ca_translates_iso0_to_iso4_aes():
    """Translate a DES ISO-0 PIN block into an AES ISO-4 block (format 48)."""
    sim, port = await _start()
    try:
        tpk = (await _send(port, "A0", "1002U"))["data"][:33]  # DES TPK
        zpk = (await _send(port, "A0", "1001R"))["data"][:33]  # AES-128 ZPK
        pan, pin = "400000000000000002", "1234"
        pan12 = "".join(c for c in pan if c.isdigit())[-13:-1]
        src = ct.pin_block_encode(pin, pan12, sim.ctx.lmk.unwrap(tpk), "0")["pin_block"]
        r = await _send(port, "CA", f"{tpk}{zpk}12{src}0148{pan12}")
        assert r["response"] == "CB" and r["error"] == "00"
        block4 = r["data"][2:34]  # ISO-4 block is 16 bytes = 32 hex
        assert len(block4) == 32
        assert ct.pin_block_decode(block4, pan12, sim.ctx.lmk.unwrap(zpk), "4")["pin"] == pin
    finally:
        await sim.stop()


async def test_ca_translates_iso4_back_to_iso0():
    """An AES ISO-4 block (32-hex) translates back to a DES ISO-0 block — the
    PIN-block field width follows the source format, both directions."""
    sim, port = await _start()
    try:
        aes_zpk = (await _send(port, "A0", "1001R"))["data"][:33]
        des_zpk = (await _send(port, "A0", "1001U"))["data"][:33]
        pan, pin = "400000000000000002", "1234"
        pan12 = "".join(c for c in pan if c.isdigit())[-13:-1]
        block4 = ct.pin_block_encode(pin, pan12, sim.ctx.lmk.unwrap(aes_zpk), "4")["pin_block"]
        # src fmt 48 (ISO-4, AES) -> dst fmt 01 (ISO-0, DES)
        r = await _send(port, "CA", f"{aes_zpk}{des_zpk}12{block4}4801{pan12}")
        assert r["response"] == "CB" and r["error"] == "00"
        out0 = r["data"][2:18]
        assert ct.pin_block_decode(out0, pan12, sim.ctx.lmk.unwrap(des_zpk), "0")["pin"] == pin
    finally:
        await sim.stop()


async def test_de_generate_then_ba_verifies_ibm_offset():
    sim, port = await _start()
    try:
        tpk = (await _send(port, "A0", "1002U"))["data"][:33]
        pvk = (await _send(port, "A0", "1002U"))["data"][:33]
        pan, pin = "400000000000000002", "1234"
        dec, val = "0123456789012345", "1122334455667788"
        clear_tpk = sim.ctx.lmk.unwrap(tpk)
        block = ct.pin_block_encode(pin, pan, clear_tpk)["pin_block"]
        pan12 = "".join(c for c in pan if c.isdigit())[-13:-1]
        gen = await _send(port, "DE", f"{tpk}{pvk}{block}01{pan12}{dec}{val}")
        assert gen["response"] == "DF" and gen["error"] == "00"
        offset = gen["data"]
        assert offset and offset.isdigit()
        # BA with the correct offset verifies; a mangled offset is rejected.
        ok = await _send(port, "BA", f"{tpk}{pvk}{block}01{pan12}{dec}{val}{offset}")
        assert ok["response"] == "BB" and ok["error"] == "00"
        bad_off = str((int(offset[0]) + 1) % 10) + offset[1:]
        bad = await _send(port, "BA", f"{tpk}{pvk}{block}01{pan12}{dec}{val}{bad_off}")
        assert bad["error"] == "01"
    finally:
        await sim.stop()


