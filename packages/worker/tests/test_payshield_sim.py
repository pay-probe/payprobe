"""payShield 10K simulator — driven over a real socket with framed commands.

Validates the wire format (length prefix + echoed header + response/error code)
and the hybrid crypto: keys minted by A0 check out under BU, a CVV generated by
CW verifies under CY (and a wrong one is rejected), a PIN translated TPK->ZPK by
CA decodes back to the same PIN, EC verifies a PVV, and M6/M8 round-trip a MAC.
"""

import asyncio

from worker.adapters.hsm.payshield import PayShieldSimulator
from worker.engine import crypto_tools as ct

HEADER = "HDR1"


async def _start(config=None):
    sim = PayShieldSimulator(config or {"host": "127.0.0.1", "port": 0})
    port = await sim.start()
    return sim, port


async def _send(port: int, command: str, data: str = "") -> dict:
    """Send one framed payShield command, return the decoded response dict."""
    reader, writer = await asyncio.open_connection("127.0.0.1", port)
    body = f"{HEADER}{command}{data}".encode("ascii")
    writer.write(len(body).to_bytes(2, "big") + body)
    await writer.drain()
    prefix = await reader.readexactly(2)
    resp = await reader.readexactly(int.from_bytes(prefix, "big"))
    writer.close()
    text = resp.decode("ascii")
    return {
        "header": text[:4],
        "response": text[4:6],
        "error": text[6:8],
        "data": text[8:],
    }


async def test_nc_diagnostics():
    sim, port = await _start()
    try:
        r = await _send(port, "NC")
        assert r["header"] == HEADER
        assert r["response"] == "ND"
        assert r["error"] == "00"
        # 16-digit LMK check value + 9-char firmware "xxxx-xxxx".
        assert len(r["data"]) == 25
        assert r["data"][20] == "-"  # firmware "xxxx-xxxx" dash
    finally:
        await sim.stop()


async def test_a0_generate_then_bu_checks_out():
    sim, port = await _start()
    try:
        gen = await _send(port, "A0", "1002U")  # mode 1, TPK (002), double-length
        assert gen["response"] == "A1" and gen["error"] == "00"
        token, kcv = gen["data"][:33], gen["data"][33:39]
        assert token[0] == "U" and len(kcv) == 6
        # BU on the same token must reproduce the KCV A0 returned.
        chk = await _send(port, "BU", "00" + "1" + token)
        assert chk["response"] == "BV" and chk["error"] == "00"
        assert chk["data"][:6] == kcv
    finally:
        await sim.stop()


async def test_cw_then_cy_verifies_and_rejects():
    sim, port = await _start()
    try:
        cvk = (await _send(port, "A0", "1402U"))["data"][:33]  # CVK (402)
        pan, expiry, sc = "4000000000000002", "2512", "000"
        gen = await _send(port, "CW", f"{cvk}{pan};{expiry}{sc}")
        assert gen["response"] == "CX" and gen["error"] == "00"
        cvv = gen["data"]
        assert len(cvv) == 3 and cvv.isdigit()
        ok = await _send(port, "CY", f"{cvk}{cvv}{pan};{expiry}{sc}")
        assert ok["response"] == "CZ" and ok["error"] == "00"
        bad = await _send(port, "CY", f"{cvk}999{pan};{expiry}{sc}")
        assert bad["error"] == "01"
    finally:
        await sim.stop()


async def test_ca_pin_translate_round_trips():
    sim, port = await _start()
    try:
        tpk = (await _send(port, "A0", "1002U"))["data"][:33]
        zpk = (await _send(port, "A0", "1001U"))["data"][:33]
        pan, pin = "400000000000000002", "1234"
        # build an ISO-0 PIN block under the clear TPK to feed the simulator
        clear_tpk = sim.ctx.lmk.unwrap(tpk)
        src_block = ct.pin_block_encode(pin, pan, clear_tpk)["pin_block"]
        pan12 = "".join(c for c in pan if c.isdigit())[-13:-1]
        r = await _send(port, "CA", f"{tpk}{zpk}12{src_block}0101{pan12}")
        assert r["response"] == "CB" and r["error"] == "00"
        out_len, out_block = r["data"][:2], r["data"][2:18]
        assert out_len == "04"
        clear_zpk = sim.ctx.lmk.unwrap(zpk)
        assert ct.pin_block_decode(out_block, pan, clear_zpk)["pin"] == pin
    finally:
        await sim.stop()


